-- E1 probe v2: fs.move semantics for directory into itself, prefix-sibling, and log-style rename.
fs.makeDir("a")
fs.makeDir("a/b")
local ok, err = pcall(fs.move, "a", "a/x")
print("inside-self", ok, tostring(err))
print("a", fs.exists("a"), "a/x", fs.exists("a/x"), "a/b", fs.exists("a/b"))
fs.makeDir("d")
local ok2, err2 = pcall(fs.move, "d", "de")
print("prefix-sibling", ok2, tostring(err2), "d", fs.exists("d"), "de", fs.exists("de"))
fs.makeDir("f")
fs.makeDir("f/x")
local ok3, err3 = pcall(fs.move, "f/x", "f")
print("child-to-parent", ok3, tostring(err3), "f", fs.exists("f"), "f/x", fs.exists("f/x"))
local h = assert(fs.open("a.log", "w")); h.write("x"); h.close()
local ok4, err4 = pcall(fs.move, "a.log", "a.log.1")
print("prefix-file", ok4, tostring(err4), "a.log", fs.exists("a.log"), "a.log.1", fs.exists("a.log.1"))
